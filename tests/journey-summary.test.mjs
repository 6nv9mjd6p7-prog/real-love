import ts from 'typescript';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
const require=createRequire(import.meta.url);
const js=ts.transpileModule(readFileSync('app/journey-summary.tsx','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,jsx:ts.JsxEmit.ReactJSX}}).outputText.replace(/from ["']react\/jsx-runtime["']/,`from '${pathToFileURL(require.resolve('react/jsx-runtime')).href}'`);
const {default:Summary,journeyRate}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
assert.equal(journeyRate(1,2),'50%');assert.equal(journeyRate(0,0),'—');
const approval={approved:2,discovered:2,viewed:1,chatted:1,invited:1,accepted:1,messaged:1,conversations:1,returned:1};
const signup={started:2,basics:2,interests:1,saved:1};
const html=renderToStaticMarkup(React.createElement(Summary,{approval,signup}));
assert(html.includes('1 / 2 · 50%'));assert(html.includes('2 / 2 · 100%'));
assert(html.includes('not consecutive conversion rates'));assert(html.includes('does not measure quality or safety'));
assert(html.includes('Screen views do not prove'));assert(html.includes('Earlier actions are not backfilled'));
const empty=renderToStaticMarkup(React.createElement(Summary,{approval:{...approval,approved:0},signup:{...signup,started:0}}));
assert(!empty.includes('NaN%'));assert(empty.includes('No completed observation windows yet.'));
console.log('Journey denominators, percentage display, empty windows and measurement limitations passed.');
