import ts from 'typescript';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
const require=createRequire(import.meta.url);
const code=ts.transpileModule(readFileSync('app/chat-row.tsx','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,jsx:ts.JsxEmit.ReactJSX}}).outputText.replace('from "react/jsx-runtime"',`from '${pathToFileURL(require.resolve('react/jsx-runtime')).href}'`);
const {default:Row,chatListTimestamp}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const chat={context:{label:'Something I’m curious about…',text:'Music'},person:{name:'Alex'},unread:2,lastMessage:{mine:true,body:'A long preview',created:'2026-10-11T08:00:00Z'}};
const render=c=>renderToStaticMarkup(React.createElement(Row,{chat:c,onOpen:()=>{},avatar:React.createElement('button',null,'Profile')}));
const html=render(chat),open=html.slice(html.indexOf('class="chat-row-open"'));
assert.match(open,/Alex/);assert.match(open,/You: A long preview/);assert.match(open,/<time/);assert.match(open,/2 unread messages/);assert(!open.includes('Profile'),'profile control remains outside the chat button');assert.equal((html.match(/<button/g)||[]).length,2);
assert(!html.includes('Something I’m curious')&&!html.includes('Music'),'opening profile context is not repeated in the chat list');
assert(render({...chat,lastMessage:null}).includes('Say hello'),'empty chats have a clear greeting instead of a profile prompt');
const unavailable=render({...chat,available:false});assert.match(unavailable,/safety options/);assert(!unavailable.includes('A long preview'));
console.log('Chat button includes name, preview, timestamp and unread label; separate profile control and unavailable preview protection passed.');

const now=new Date(2026,9,16,12,30);
assert.equal(chatListTimestamp(new Date(2026,9,16,8,15).toISOString(),now),new Date(2026,9,16,8,15).toLocaleTimeString([],{hour:'2-digit',minute:'2-digit'}));
assert.equal(chatListTimestamp(new Date(2026,9,15,23,59).toISOString(),now),'Yesterday');
assert.equal(chatListTimestamp(new Date(2025,9,14,8).toISOString(),now),new Date(2025,9,14,8).toLocaleDateString([],{month:'short',day:'numeric',year:'numeric'}));
assert.equal(chatListTimestamp(new Date(2025,11,31,20).toISOString(),new Date(2026,0,1,1)),'Yesterday','calendar-day comparison crosses the year boundary');
assert.equal(chatListTimestamp('invalid',now),'');
assert(html.includes('title="'),'exact local timestamp remains available');
assert(html.includes('chat-unread'),'unread messages have a visual emphasis hook');
