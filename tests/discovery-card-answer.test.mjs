import ts from 'typescript';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
const require=createRequire(import.meta.url);
const code=ts.transpileModule(readFileSync('app/discovery-card-answer.tsx','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,jsx:ts.JsxEmit.ReactJSX}}).outputText.replace(/from ["']react\/jsx-runtime["']/,`from '${pathToFileURL(require.resolve('react/jsx-runtime')).href}'`);
const {default:Answer}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const person={question:'Why do people become tribal?',perspective:'Perspective answer',care:'Care answer',startIdea:'Explore answer',about:'Long introduction'};
const render=p=>renderToStaticMarkup(React.createElement(Answer,{person:p}));
const html=render(person);assert(html.includes('Why do people become tribal?'));assert(!html.includes('Long introduction'));assert(!html.includes('Perspective answer'),'only one intellectual answer appears');
assert(render({...person,question:'  '}).includes('Perspective answer'),'blank answers do not displace meaningful content');
assert(render({...person,question:'',perspective:'',care:''}).includes('Explore answer'));
const sparse=render({about:'Introduction only'});assert(sparse.includes('Introduction only')&&!sparse.includes('discovery-thought'),'sparse profiles still introduce the person');
assert(render({about:'a'.repeat(200)}).includes('…'),'introduction fallback remains bounded');
assert.equal(person.about,'Long introduction','card selection does not remove profile data');
console.log('Discovery cards show one meaningful answer with an introduction fallback and preserve the original profile.');
