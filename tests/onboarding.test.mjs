import ts from 'typescript';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const source=ts.transpileModule(readFileSync('app/onboarding.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {onboardingNext}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const base={me:null,account:{status:'pending'},canConnect:false,incoming:0,sent:0,rulesVersion:'current'};
assert.equal(onboardingNext(base).destination,'profile');
assert.equal(onboardingNext({...base,account:{status:'banned'}}).destination,'settings','restriction precedes profile creation');
const me={active:true,rulesVersion:'current'};
assert.equal(onboardingNext({...base,me}).kind,'pending');
assert.match(onboardingNext({...base,me}).detail,/no guaranteed review time/);
const admitted={...base,me,account:{status:'admitted'}};
assert.equal(onboardingNext({...admitted,me:{...me,rulesVersion:'old'}}).destination,'profile','updated rules link to editable agreement rather than Settings');
assert.equal(onboardingNext({...admitted,me:{...me,active:false}}).destination,'settings');
assert.equal(onboardingNext({...admitted,canConnect:true,incoming:1,sent:1}).kind,'incoming');
assert.equal(onboardingNext({...admitted,canConnect:true,incoming:1,sent:1}).destination,'conversations/requests','incoming requests open the actionable inbox section');
assert.equal(onboardingNext({...admitted,canConnect:true,sent:1}).kind,'sent');
assert.equal(onboardingNext({...admitted,canConnect:true,sent:1}).destination,'conversations/sent','sent invitations open their own section');
assert.equal(onboardingNext({...admitted,canConnect:true}).kind,'discover');
assert.equal(onboardingNext(admitted).kind,'unavailable','unexpected access denial never claims discovery is ready');
console.log('First-use guidance and next-action checks passed');
